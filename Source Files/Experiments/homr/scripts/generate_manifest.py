#!/usr/bin/env python3
"""
Generate the IIIF manifest (public/manifest.json) that the viewer consumes.

The manifest is the viewer's single data source. It is modeled natively
after the IIIF Presentation 3 API and uses absolute URIs built from a base
URL (configurable with --base-url) so the manifest is location-independent:

  - one canvas per page, painted by its IIIF image service
    ({base}<name>/info.json, generated by generate_iiif.py)
  - the smallest full rendition of the pyramid as the canvas thumbnail
    ({base}<name>/full/<w,/0/default.jpg) — the overview grid shows
    this, scaled by the client
  - the notation files as Alternative Representations (canvas "rendering"):
    MusicXML and MNX, copied into public/musicxml/ and public/mnx/
  - OMR confidence/status/error as canvas metadata
  - each detected staff (= one system region of the scan) as a "describing"
    annotation on the page canvas: the #xywh FragmentSelector target carries
    the region, the TextualBody carries the OMR data (staff grid, line
    count) plus the linkage into the MNX (mnx reference + measure index
    range [start, end) into the MNX's global.measures)
  - the MNX document itself as a "supplementing" annotation with an inline
    TextualBody (application/json) targeting the whole page canvas

The referenced files must exist under public/ mirroring the URL paths; the
generator verifies this and fails loudly otherwise. Empty MNX files (some
pages fail the converter silently) are skipped.

Inputs:  data/results.json (homr detection) + public/<name>/info.json
Usage:   python3 scripts/generate_manifest.py [-i data/results.json] [-o public/manifest.json]
         [--base-url https://.../]
"""

from __future__ import annotations

import argparse
import json
import math
import os
import shutil
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

DEFAULT_BASE_URL = "https://static.projektemacher.org/kinderbuecher/post/vieilles-chansons-et-rondes/"
MUSICXML_FORMAT = "application/vnd.recordare.musicxml+xml"
MNX_FORMAT = "application/json"


def abs_url(base: str, path: str) -> str:
    """Absolute URI for a root-relative path (base always ends with '/')."""
    return base + path.lstrip("/")


def url_to_public_path(base: str, url: str, public: str) -> str | None:
    """Filesystem path under public/ for an absolute URL (fragment dropped)."""
    if not url.startswith(base):
        return None
    rel = url[len(base):].split("#", 1)[0]
    return os.path.join(public, rel)


def static_full_rendition(pyramid_dir: str, info: dict, width: int) -> tuple[str, str] | None:
    """Smallest static full rendition of a pyramid: (URL part, filesystem path)."""
    scales = [sf for t in info.get("tiles", []) for sf in t.get("scaleFactors", [])]
    if not scales:
        return None
    small = max(1, math.ceil(width / max(scales)))
    url = f"full/{small},/0/default.jpg"
    fs = os.path.join(pyramid_dir, "full", f"{small},", "0", "default.jpg")
    return (url, fs) if os.path.exists(fs) else None


def language_value(value: str) -> dict:
    """Presentation 3 language map."""
    return {"en": [value]}


def system_measure_ranges(xml_path: str) -> tuple[list[list[int]], int] | None:
    """Measure index ranges [start, end) per system of a MusicXML part.

    Systems break at <print new-system="yes">; the first system starts at
    measure 0. Returns (ranges, measure count) or None when unparseable.
    """
    try:
        root = ET.parse(xml_path).getroot()
    except ET.ParseError:
        return None
    part = root.find("part")
    if part is None:
        return None
    measures = part.findall("measure")
    ranges: list[list[int]] = []
    start = 0
    for idx, measure in enumerate(measures):
        print_el = measure.find("print")
        if print_el is not None and print_el.get("new-system") == "yes" and idx > start:
            ranges.append([start, idx])
            start = idx
    ranges.append([start, len(measures)])
    return (ranges, len(measures))


def load_mnx(path: str) -> tuple[str, int] | None:
    """Read an MNX file: (text, measure count). None when empty/invalid."""
    try:
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
    except OSError:
        return None
    if not text.strip():
        return None
    try:
        doc = json.loads(text)
    except json.JSONDecodeError:
        return None
    count = len(doc.get("global", {}).get("measures", []))
    return (text, count)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-i", "--input", default="data/results.json")
    parser.add_argument("-o", "--output", default="public/manifest.json")
    parser.add_argument("--base-url", default=DEFAULT_BASE_URL, help="base URL for all IIIF URIs")
    args = parser.parse_args()

    base = args.base_url if args.base_url.endswith("/") else args.base_url + "/"
    results_path = os.path.join(ROOT, args.input)
    out_path = os.path.join(ROOT, args.output)
    public = os.path.dirname(out_path)

    with open(results_path, encoding="utf-8") as fh:
        results = json.load(fh)
    pages = results.get("pages", [])
    if not pages:
        print(f"No pages in {results_path}", file=sys.stderr)
        sys.exit(1)

    items: list[dict] = []
    failures: list[str] = []
    for page in pages:
        name = os.path.splitext(page["image"])[0]
        width, height = page["width"], page["height"]

        pyramid_dir = os.path.join(public, name)
        info_fs = os.path.join(pyramid_dir, "info.json")
        if not os.path.exists(info_fs):
            failures.append(f"{name}: no IIIF pyramid (run generate_iiif.py first)")
            continue
        with open(info_fs, encoding="utf-8") as fh:
            info = json.load(fh)

        # the pyramid's info.json carries the actual IIIF Image API id; keep
        # it in sync with the base URL so a base change does not require
        # regenerating the slow pyramid step
        expected_service_id = abs_url(base, name)
        if info.get("@id") != expected_service_id:
            info["@id"] = expected_service_id
            with open(info_fs, "w", encoding="utf-8") as fh:
                json.dump(info, fh, indent=2)
        service_id = expected_service_id

        rendition = static_full_rendition(pyramid_dir, info, width)
        if rendition is None:
            failures.append(f"{name}: no static full rendition for thumbnails")
            continue
        thumb_rel, _thumb_fs = rendition
        thumb_url = f"{service_id}/{thumb_rel}"
        if not os.path.exists(url_to_public_path(base, thumb_url, public) or ""):
            failures.append(f"{name}: thumbnail {thumb_rel} missing on disk")
            continue

        # notation files: copy into public/ so the manifest's references are
        # static and the public/ folder alone is deployable
        homr = page.get("homr") or {}
        musicxml_url = None
        musicxml_src = homr.get("musicxml")
        source_musicxml = None
        if musicxml_src:
            source_musicxml = os.path.normpath(os.path.join(ROOT, musicxml_src))
            if os.path.exists(source_musicxml):
                dest_dir = os.path.join(public, "musicxml")
                os.makedirs(dest_dir, exist_ok=True)
                shutil.copy2(source_musicxml, os.path.join(dest_dir, os.path.basename(source_musicxml)))
                musicxml_url = abs_url(base, f"musicxml/{os.path.basename(source_musicxml)}")
            else:
                print(f"WARNING: {name}: MusicXML {source_musicxml} not found", file=sys.stderr)
                source_musicxml = None

        # MNX: skip empty/invalid files (some pages fail the converter
        # silently and would otherwise produce broken references)
        mnx_url = None
        mnx_text = None
        mnx_measure_count = None
        mnx_src = os.path.join(ROOT, name + ".mnx")
        if os.path.exists(mnx_src):
            loaded = load_mnx(mnx_src)
            if loaded is None:
                print(f"WARNING: {name}: MNX file empty or invalid, skipped", file=sys.stderr)
            else:
                mnx_text, mnx_measure_count = loaded
                dest_dir = os.path.join(public, "mnx")
                os.makedirs(dest_dir, exist_ok=True)
                shutil.copy2(mnx_src, os.path.join(dest_dir, os.path.basename(mnx_src)))
                mnx_url = abs_url(base, f"mnx/{os.path.basename(mnx_src)}")

        rendering: list[dict] = []
        if musicxml_url:
            rendering.append(
                {
                    "id": musicxml_url,
                    "type": "Text",
                    "format": MUSICXML_FORMAT,
                    "label": language_value("MusicXML"),
                }
            )
        if mnx_url:
            rendering.append(
                {
                    "id": mnx_url,
                    "type": "Dataset",
                    "format": MNX_FORMAT,
                    "label": language_value("MNX"),
                }
            )

        # native descriptive metadata for the OMR run (display + viewer)
        metadata = []
        if rendering:
            confidence = page.get("confidence", 0)
            confidence_str = (
                f"{confidence * 100:.1f}%"
                if isinstance(confidence, (int, float)) and math.isfinite(confidence)
                else "n/a"
            )
            metadata.append({"label": language_value("OMR confidence"), "value": language_value(confidence_str)})
            if homr.get("status"):
                metadata.append({"label": language_value("OMR status"), "value": language_value(str(homr["status"]))})
            if homr.get("error"):
                metadata.append({"label": language_value("OMR error"), "value": language_value(str(homr["error"]))})

        # staff annotations: one per detected staff (= one system region of
        # the scan). The #xywh target is the native region; the TextualBody
        # carries the OMR data (staff grid, line count) and — when the page
        # has a valid MNX — the linkage into it (mnx reference + measure
        # index range of the system).
        system_ranges: list[list[int]] | None = None
        if source_musicxml:
            parsed = system_measure_ranges(source_musicxml)
            if parsed is None:
                print(f"WARNING: {name}: could not parse MusicXML for system ranges", file=sys.stderr)
            else:
                system_ranges, musicxml_measure_count = parsed
        mnx_measures_ok = (
            mnx_measure_count is not None
            and system_ranges is not None
            and mnx_measure_count == musicxml_measure_count
        )
        if mnx_measure_count is not None and system_ranges is not None and not mnx_measures_ok:
            print(
                f"WARNING: {name}: MNX has {mnx_measure_count} measures but "
                f"MusicXML has {musicxml_measure_count} — skipping MNX linkage",
                file=sys.stderr,
            )

        staff_annotations: list[dict] = []
        staves = page.get("staves", [])
        for idx, staff in enumerate(staves):
            bbox = staff.get("bbox", [0, 0, 0, 0])
            x0, y0, x1, y1 = bbox
            w, h = max(0, x1 - x0), max(0, y1 - y0)
            payload: dict = {
                "staffGrid": staff.get("grid", []),
                "staffLineCount": staff.get("lineCount", 5),
            }
            if mnx_measures_ok and system_ranges and idx < len(system_ranges):
                payload["mnx"] = mnx_url
                payload["measures"] = system_ranges[idx]
            elif mnx_url and system_ranges and idx >= len(system_ranges):
                print(
                    f"WARNING: {name}: staff {idx + 1} has no matching MusicXML system "
                    f"({len(system_ranges)} systems for {len(staves)} staffs) — no MNX linkage",
                    file=sys.stderr,
                )
            staff_annotations.append(
                {
                    "id": f"{service_id}/annotation/staff-{idx + 1}",
                    "type": "Annotation",
                    "motivation": "describing",
                    "body": {
                        "type": "TextualBody",
                        "format": MNX_FORMAT,
                        "value": json.dumps(payload),
                    },
                    "target": f"{service_id}/canvas#xywh={x0},{y0},{w},{h}",
                }
            )

        canvas = {
            "id": f"{service_id}/canvas",
            "type": "Canvas",
            "label": language_value(name),
            "width": width,
            "height": height,
            "thumbnail": [{"id": thumb_url, "type": "Image", "format": "image/jpeg"}],
            "items": [
                {
                    "id": f"{service_id}/annotation-page",
                    "type": "AnnotationPage",
                    "items": [
                        {
                            "id": f"{service_id}/annotation/image",
                            "type": "Annotation",
                            "motivation": "painting",
                            "body": {
                                "id": f"{service_id}/info.json",
                                "type": "Image",
                                "service": [
                                    {
                                        "id": service_id,
                                        "type": "ImageService2",
                                        "profile": "level0",
                                    }
                                ],
                            },
                            "target": f"{service_id}/canvas",
                        }
                    ],
                }
            ],
        }
        if metadata:
            canvas["metadata"] = metadata
        if rendering:
            canvas["rendering"] = rendering

        annotation_pages = []
        if staff_annotations:
            annotation_pages.append(
                {
                    "id": f"{service_id}/annotation-page/staffs",
                    "type": "AnnotationPage",
                    "items": staff_annotations,
                }
            )
        if mnx_text:
            annotation_pages.append(
                {
                    "id": f"{service_id}/annotation-page/mnx",
                    "type": "AnnotationPage",
                    "items": [
                        {
                            "id": f"{service_id}/annotation/mnx",
                            "type": "Annotation",
                            "motivation": "supplementing",
                            "body": {"type": "TextualBody", "format": MNX_FORMAT, "value": mnx_text},
                            "target": f"{service_id}/canvas",
                        }
                    ],
                }
            )
        if annotation_pages:
            canvas["annotations"] = annotation_pages
        items.append(canvas)

    if failures:
        for f in failures:
            print(f"ERROR: {f}", file=sys.stderr)
        sys.exit(1)

    manifest = {
        "@context": "http://iiif.io/api/presentation/3/context.json",
        "id": abs_url(base, "manifest.json"),
        "type": "Manifest",
        "label": {"en": ["Score pages (kinderbücher)"]},
        "behavior": ["paged"],
        "items": items,
    }
    os.makedirs(public, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)
    print(f"Wrote {out_path} ({len(items)} canvases, base {base})")


if __name__ == "__main__":
    main()
