#!/usr/bin/env python3
"""Generate per-page TEI wrappers (public/tei/pageNNN.tei.xml) from the homr results.

Each TEI file is the single source of staff geometry for one scanned page and
embeds that page's MusicXML verbatim:

  - <teiHeader> with the source/Omr metadata
  - <facsimile> with one <surface> (the page, coordinates in original image
    pixels, corresp = the IIIF canvas) and one <zone type="staff"> per
    detected staff: the staff bounding box as @ulx/@uly/@lrx/@lry plus each
    staff line as a <path points="x,y ..."> polyline (homr's staff grid)
  - <text>/<body>/<div type="score"> with the page's <score-partwise>
    document embedded verbatim (no namespace; its XML declaration and DOCTYPE
    are stripped, everything from the root element on is carried as-is)

The output is validated against the official TEI schema compiled from
schema/homr-tei.odd (Relax NG + ISO Schematron, see schema/VENDORING.md)
and the embedded MusicXML against the official MusicXML 4.0 XSD
(report only; see scripts/validate_tei.py). Any validation error fails the
run.

Inputs:  data/results.json (homr detection) + pageNNN.musicxml
Usage:   python3 scripts/generate_tei.py [-i data/results.json] [-o public/tei]
         [--base-url https://.../]
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from validate_tei import load_musicxml_xsd, load_rng, schematron_from_rng, validate_file  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_BASE_URL = "https://static.projektemacher.org/kinderbuecher/post/vieilles-chansons-et-rondes/"
DEFAULT_BOOK_TITLE = "Vieilles Chansons et Danses et Rondes"

PROLOG = '<?xml version="1.0" encoding="UTF-8"?>\n'


def abs_url(base: str, path: str) -> str:
    """Absolute URI for a root-relative path (base always ends with '/')."""
    return base + path.lstrip("/")


def musicxml_root(xml_text: str) -> str | None:
    """Everything from the MusicXML root element on, verbatim: the source
    files carry xmlns="" already (see normalize_musicxml_namespace in
    run_homr.py), so they embed cleanly under the TEI default namespace.
    The XML declaration and DOCTYPE cannot live inside another document and
    stay out."""
    match = re.search(r"<score-partwise(?=[\s>])[^>]*>", xml_text)
    if match is None:
        return None
    if "xmlns" not in match.group(0):
        print(
            "ERROR: MusicXML root has no namespace declaration "
            "(run scripts/run_homr.py to normalize the homr output)",
            file=sys.stderr,
        )
        return None
    return xml_text[match.start() :]


def musicxml_title(xml_path: str) -> str | None:
    """<work-title> of a MusicXML file, if parseable."""
    try:
        root = ET.parse(xml_path).getroot()
        work_title = root.find("work/work-title")
        if work_title is not None and work_title.text:
            return work_title.text.strip()
    except ET.ParseError:
        pass
    return None


def staff_paths(staff: dict) -> list[str]:
    """One <path points="x,y ..."> polyline per staff line of the grid."""
    grid = staff.get("grid", [])
    if not grid:
        return []
    line_count = min(len(pt.get("y", [])) for pt in grid)
    paths = []
    for k in range(line_count):
        points = " ".join(f"{pt['x']},{pt['y'][k]}" for pt in grid)
        paths.append(f'        <path type="staff-line" points="{points}"/>')
    return paths


def build_tei(
    name: str,
    page: dict,
    musicxml: str,
    musicxml_path: str,
    base: str,
    book_title: str,
) -> str:
    """Assemble the TEI document for one page."""
    title = musicxml_title(musicxml_path) or name
    canvas = abs_url(base, f"{name}/canvas")
    service = abs_url(base, f"{name}/info.json")
    width, height = page["width"], page["height"]

    header = f"""<TEI xmlns="http://www.tei-c.org/ns/1.0">
  <teiHeader>
    <fileDesc>
      <titleStmt>
        <title>{title} ({book_title}, {name})</title>
        <respStmt>
          <resp>Encoded from the optical music recognition output of</resp>
          <name>homr</name>
        </respStmt>
      </titleStmt>
      <publicationStmt>
        <publisher>Projektemacher</publisher>
        <availability status="free">
          <p>Freely available for use and reuse. Generated by
          scripts/generate_tei.py from data/results.json.</p>
        </availability>
      </publicationStmt>
      <sourceDesc>
        <bibl>
          <title>{book_title}</title>
          <ptr target="{canvas}"/>
        </bibl>
      </sourceDesc>
    </fileDesc>
    <encodingDesc>
      <appInfo>
        <application version="1" ident="homr">
          <label>homr</label>
          <p>Optical music recognition (homr) detected {len(page.get("staves", []))} staff(s)
          on this page; their regions and staff-line paths are encoded in the
          facsimile below. The MusicXML produced by homr is embedded in the
          body. IIIF image service: {service}</p>
        </application>
      </appInfo>
    </encodingDesc>
  </teiHeader>
  <facsimile>
    <surface ulx="0" uly="0" lrx="{width}" lry="{height}" corresp="{canvas}">
      <graphic url="{service}"/>"""

    body = []
    for idx, staff in enumerate(page.get("staves", [])):
        x0, y0, x1, y1 = staff.get("bbox", [0, 0, 0, 0])
        body.append(
            f'      <zone xml:id="{name}-staff-{idx + 1}" type="staff" '
            f'ulx="{x0}" uly="{y0}" lrx="{x1}" lry="{y1}">'
        )
        body.extend(staff_paths(staff))
        body.append("      </zone>")
    zones = "\n".join(body)

    return (
        PROLOG
        + header
        + "\n"
        + zones
        + f"""
    </surface>
  </facsimile>
  <text>
    <body>
      <div type="score">
{musicxml}
      </div>
    </body>
  </text>
</TEI>
"""
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-i", "--input", default="data/results.json")
    parser.add_argument("-o", "--output", default="public/tei")
    parser.add_argument("--base-url", default=DEFAULT_BASE_URL, help="base URL for the IIIF references")
    parser.add_argument(
        "--book-title", default=DEFAULT_BOOK_TITLE, help="book title for the TEI headers"
    )
    parser.add_argument("--rng", default=os.path.join(ROOT, "schema", "homr-tei.rng"))
    parser.add_argument("--musicxml-xsd", default=os.path.join(ROOT, "vendor", "musicxml", "schema", "musicxml.xsd"))
    args = parser.parse_args()

    base = args.base_url if args.base_url.endswith("/") else args.base_url + "/"

    results_path = os.path.join(ROOT, args.input)
    with open(results_path, encoding="utf-8") as fh:
        results = json.load(fh)
    pages = results.get("pages", [])
    if not pages:
        print(f"No pages in {results_path}", file=sys.stderr)
        sys.exit(1)

    out_dir = os.path.join(ROOT, args.output)
    os.makedirs(out_dir, exist_ok=True)

    # clean regeneration: drop artifacts of pages that no longer generate
    for stale in os.listdir(out_dir):
        if stale.endswith(".tei.xml"):
            os.unlink(os.path.join(out_dir, stale))

    rng = load_rng(args.rng)
    schematron = schematron_from_rng(args.rng)
    xsd = load_musicxml_xsd(args.musicxml_xsd)

    written = 0
    failures: list[str] = []
    for page in pages:
        name = os.path.splitext(page["image"])[0]
        musicxml_src = (page.get("homr") or {}).get("musicxml")
        if not musicxml_src:
            continue  # not a score page
        if not page.get("staves"):
            failures.append(f"{name}: has MusicXML but no staff regions")
            continue
        source_musicxml = os.path.normpath(os.path.join(ROOT, musicxml_src))
        try:
            with open(source_musicxml, encoding="utf-8") as fh:
                xml_text = fh.read()
        except OSError as exc:
            print(f"WARNING: {name}: MusicXML unreadable, skipped: {exc}", file=sys.stderr)
            continue
        if not xml_text.strip():
            print(f"WARNING: {name}: MusicXML file empty, skipped", file=sys.stderr)
            continue
        musicxml = musicxml_root(xml_text)
        if musicxml is None:
            failures.append(f"{name}: MusicXML has no <score-partwise> root")
            continue

        out_path = os.path.join(out_dir, f"{name}.tei.xml")
        with open(out_path, "w", encoding="utf-8") as fh:
            fh.write(build_tei(name, page, musicxml, source_musicxml, base, args.book_title))

        errors, warnings = validate_file(out_path, rng, schematron, xsd, strict_musicxml=False)
        for warning in warnings:
            print(f"WARNING: {warning}", file=sys.stderr)
        if errors:
            os.unlink(out_path)
            for error in errors:
                print(f"ERROR: {name}: {error}", file=sys.stderr)
            failures.append(f"{name}: generated TEI failed validation")
            continue
        written += 1
        print(f"  {name}: {len(page['staves'])} staff(s) -> {out_path}")

    if failures:
        for failure in failures:
            print(f"ERROR: {failure}", file=sys.stderr)
        sys.exit(1)
    print(f"Wrote {written} TEI file(s) to {out_dir}")


if __name__ == "__main__":
    main()
